import { z } from 'zod';
import { sanitizeLine, sanitizeMultiline } from '../../shared/text.js';
import { HEADLINE_TARGET_ID, SUMMARY_TARGET_ID } from './cv.types.js';

/**
 * Limits from docs/API.md. They apply to manual edits (PATCH) and to LLM output alike:
 * the generation module must run model output through `cvContentSchema` before storing it.
 */
export const CV_CONTENT_LIMITS = {
  experienceItems: 30,
  bulletsPerItem: 15,
  educationItems: 15,
  skillGroups: 20,
  skillsPerGroup: 40,
  links: 10,
  text: 300,
  summary: 1500,
  bullet: 400,
  educationDetails: 600,
  id: 64,
} as const;

const L = CV_CONTENT_LIMITS;

/** Trimmed single-line string; control characters stripped, line breaks become spaces. */
export const lineText = (max: number) => z.string().overwrite(sanitizeLine).max(max);

/** Trimmed multi-line string; keeps `\n`, strips other control characters. */
export const multilineText = (max: number) => z.string().overwrite(sanitizeMultiline).max(max);

/**
 * Content item id. Ids are generated by our code (LLM pipeline) or by the editor for items the
 * user adds, and are referenced by review flags, evidence and questions.
 */
export const itemIdSchema = z
  .string()
  .trim()
  .min(1)
  .max(L.id)
  .regex(/^[A-Za-z0-9_-]+$/, 'Only letters, digits, "_" and "-" are allowed');

const SAFE_URL_SCHEMES = new Set(['http:', 'https:', 'mailto:']);
const HAS_SCHEME_RE = /^[a-z][a-z0-9+.-]*:/i;

/**
 * Links are rendered into the PDF, so dangerous schemes (javascript:, data:, file:) are rejected.
 * Scheme-less values ("github.com/jane") are allowed; the renderer decides how to link them.
 */
export const linkUrlSchema = lineText(L.text).refine(
  (value) => {
    const scheme = HAS_SCHEME_RE.exec(value)?.[0].toLowerCase();
    return scheme === undefined || SAFE_URL_SCHEMES.has(scheme);
  },
  { message: 'Only http, https and mailto links are allowed' },
);

export const bulletSchema = z.object({
  id: itemIdSchema,
  text: lineText(L.bullet),
});

export const experienceItemSchema = z.object({
  id: itemIdSchema,
  company: lineText(L.text),
  title: lineText(L.text),
  location: lineText(L.text),
  startDate: lineText(L.text),
  endDate: lineText(L.text),
  bullets: z.array(bulletSchema).max(L.bulletsPerItem),
});

export const educationItemSchema = z.object({
  id: itemIdSchema,
  institution: lineText(L.text),
  degree: lineText(L.text),
  location: lineText(L.text),
  startDate: lineText(L.text),
  endDate: lineText(L.text),
  details: multilineText(L.educationDetails),
});

export const skillGroupSchema = z.object({
  id: itemIdSchema,
  name: lineText(L.text),
  items: z.array(lineText(L.text)).max(L.skillsPerGroup),
});

export const cvLinkSchema = z.object({
  id: itemIdSchema,
  label: lineText(L.text),
  url: linkUrlSchema,
});

export const contactSchema = z.object({
  fullName: lineText(L.text),
  headline: lineText(L.text),
  email: lineText(L.text),
  phone: lineText(L.text),
  location: lineText(L.text),
  links: z.array(cvLinkSchema).max(L.links),
});

export const cvContentSchema = z
  .object({
    contact: contactSchema,
    summary: multilineText(L.summary),
    experience: z.array(experienceItemSchema).max(L.experienceItems),
    education: z.array(educationItemSchema).max(L.educationItems),
    skills: z.array(skillGroupSchema).max(L.skillGroups),
  })
  .superRefine((content, ctx) => {
    // Flags, evidence and questions reference items by id, so ids must be unique across the
    // whole document and must not collide with the reserved targets 'summary' / 'headline'.
    const seen = new Set<string>([SUMMARY_TARGET_ID, HEADLINE_TARGET_ID]);
    for (const { id, path } of collectIds(content)) {
      if (seen.has(id)) {
        ctx.addIssue({ code: 'custom', path: [...path, 'id'], message: `Duplicate id "${id}"` });
      }
      seen.add(id);
    }
  });

export type CvContent = z.output<typeof cvContentSchema>;
export type ExperienceItem = CvContent['experience'][number];
export type EducationItem = CvContent['education'][number];
export type SkillGroup = CvContent['skills'][number];
export type Bullet = ExperienceItem['bullets'][number];

function* collectIds(
  content: Pick<CvContent, 'contact' | 'experience' | 'education' | 'skills'>,
): Generator<{ id: string; path: (string | number)[] }> {
  for (const [i, link] of content.contact.links.entries()) {
    yield { id: link.id, path: ['contact', 'links', i] };
  }
  for (const [i, item] of content.experience.entries()) {
    yield { id: item.id, path: ['experience', i] };
    for (const [j, bullet] of item.bullets.entries()) {
      yield { id: bullet.id, path: ['experience', i, 'bullets', j] };
    }
  }
  for (const [i, item] of content.education.entries()) {
    yield { id: item.id, path: ['education', i] };
  }
  for (const [i, group] of content.skills.entries()) {
    yield { id: group.id, path: ['skills', i] };
  }
}
